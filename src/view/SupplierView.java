    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int baris = jTable1.getSelectedRow();
        if (baris != -1) {
            int modelRow = jTable1.convertRowIndexToModel(baris);
            javax.swing.table.TableModel model = jTable1.getModel();
            jTextField1.setText(model.getValueAt(modelRow, 2).toString());
            jTextField2.setText(model.getValueAt(modelRow, 3).toString());
            jTextField3.setText(model.getValueAt(modelRow, 4).toString());
        }
    }//GEN-LAST:event_jTable1MouseClicked

