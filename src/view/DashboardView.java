    private void muatDashboard() {
        try {
            Connection conn = KoneksiDatabase.getConnection();
            if (conn == null) {
                return;
            }

            jLabel6.setText("<html><center>Total Obat<br>" + hitung(conn, "SELECT COUNT(*) FROM obat") + "</center></html>");
            jLabel7.setText("<html><center>Supplier<br>" + hitung(conn, "SELECT COUNT(*) FROM supplier") + "</center></html>");
            jLabel8.setText("<html><center>Pembelian<br>Rp " + hitung(conn, "SELECT COALESCE(SUM(total_harga), 0) FROM pembelian") + "</center></html>");
            jLabel9.setText("<html><center>Penjualan<br>Rp " + hitung(conn, "SELECT COALESCE(SUM(total_harga), 0) FROM penjualan") + "</center></html>");

            muatStokObat(conn);
            muatObatExpired(conn);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data dashboard: " + e.getMessage());
        }
    }

    private int hitung(Connection conn, String sql) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            return rs.next() ? rs.getInt(1) : 0;
        }
    }

    private void muatStokObat(Connection conn) throws SQLException {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        String sql = "SELECT nama_obat, stok FROM obat ORDER BY stok ASC, nama_obat LIMIT 10";
        try (PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{rs.getString("nama_obat"), rs.getInt("stok")});
            }
        }
    }

    private void muatObatExpired(Connection conn) throws SQLException {
        DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
        model.setRowCount(0);
        String sql = "SELECT nama_obat, tanggal_kadaluarsa FROM obat "
                + "WHERE tanggal_kadaluarsa <= DATE_ADD(CURDATE(), INTERVAL 60 DAY) "
                + "ORDER BY tanggal_kadaluarsa ASC LIMIT 10";
        try (PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{rs.getString("nama_obat"), rs.getDate("tanggal_kadaluarsa")});
            }
        }
    }
    
    

