    private void aktifkanKlikTabel() {
        jTable1.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int viewRow = jTable1.getSelectedRow();
                if (viewRow == -1) {
                    return;
                }
                int row = jTable1.convertRowIndexToModel(viewRow);
                Object idObj = jTable1.getModel().getValueAt(row, 1);
                if (idObj == null) {
                    return;
                }
                try {
                    int idPembelian = Integer.parseInt(idObj.toString());
                    pembelianController.muatUntukEdit(idPembelian);
                } catch (NumberFormatException e) {
                    // Abaikan jika ID pada tabel tidak valid
                }
            }
        });
    }

    private void aktifkanPencarian() {
        javax.swing.table.TableRowSorter<javax.swing.table.TableModel> sorter =
                new javax.swing.table.TableRowSorter<>(jTable1.getModel());
        jTable1.setRowSorter(sorter);
        jTextField7.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent evt) {
                if ("Cari transaksi...".equals(jTextField7.getText())) {
                    jTextField7.setText("");
                }
            }
        });
        jTextField7.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
            private void filter() {
                String keyword = jTextField7.getText().trim();
                if (keyword.isEmpty() || "Cari transaksi...".equals(keyword)) {
                    sorter.setRowFilter(null);
                } else {
                    sorter.setRowFilter(javax.swing.RowFilter.regexFilter("(?i)" + java.util.regex.Pattern.quote(keyword)));
                }
            }

            public void insertUpdate(javax.swing.event.DocumentEvent e) { filter(); }
            public void removeUpdate(javax.swing.event.DocumentEvent e) { filter(); }
            public void changedUpdate(javax.swing.event.DocumentEvent e) { filter(); }
        });
    }

