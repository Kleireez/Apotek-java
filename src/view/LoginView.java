    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         String username = jTextField1.getText();
    String password = new String(txtPassword.getPassword());
 
    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Username dan password wajib diisi!",
                "Peringatan",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }
 
    controller.LoginController loginController = new controller.LoginController();
    model.Admin admin = loginController.login(username, password);
 
    if (admin != null) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Login berhasil! Selamat datang, " + admin.getUsername()
        );
        new view.DashboardView().setVisible(true);
        this.dispose();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Username atau password salah!",
                "Login Gagal",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_jButton1ActionPerformed

